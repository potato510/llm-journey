# ═══════════════════════════════════════════════════════════════════
# 变量与类型
#   name = "小明"          # str
#   age = 25               # int
#   price = 9.9            # float
#   ok = True              # bool
#   类型转换：int("25") / float("1.5") / str(25)
#   ⚠ input() 返回的永远是字符串，数字要自己 int() 转
#
# 数字运算
#   + - * /           # / 结果带小数：7 / 2 → 3.5
#   //  %  **        # 整除 / 余数 / 幂：7//2→3  7%2→1  2**10→1024
#
# 字符串
#   s = " Hello World "
#   len(s)                         # 长度（空格也算）
#   s.upper() / s.lower() / s.strip()
#   s[0] / s[-1]                   # 第一个 / 最后一个字符
#   s[::-1]                        # 反转
#   f"我叫 {name}，今年 {age} 岁"    # f-string 插值
#
# 列表（可变、有序，方括号）
#   fruits = ["苹果", "香蕉"]
#   fruits.append("橙子")          # 尾部添加
#   fruits.insert(0, "梨")         # 指定位置插入
#   fruits.remove("香蕉")          # 按值删除
#   fruits[0] / fruits[-1]         # 第一个 / 倒数第一个（索引从 0 开始）
#
# 元组（不可变，圆括号）
#   point = (3, 5)
#   point[0]                       # 3
#   point[0] = 10                  # ❌ TypeError：元组不可修改
#   用途：固定结构的值（坐标、多返回值）
#
# 字典（键值对，花括号）
#   scores = {"小明": 85, "小红": 92}
#   scores["小刚"] = 78            # 增 / 改
#   scores["小明"]                 # 取值（键不存在 → KeyError）
#   scores.get("小丽", 0)          # 安全取值，没有则返回 0
#   "小明" in scores               # 判断键是否存在
#   del scores["小红"]             # 删除
# ═══════════════════════════════════════════════════════════════════
name = input("请输入姓名：");
age = input("请输入年龄：");
print(f"你好，我叫：{name}，今年：{age}岁");
