a = input("请输入一句话：");
print(f"您输入的话是：{a}");
print(f"您输入的话的长度是：{len(a)}");
print(f"您输入的话的第一个字符是：{a[0]}");
print(f"您输入的话的最后一个字符是：{a[-1]}");
print(f"您输入的话的转成大写：{a.upper()}");
print(f"您输入的话的转成小写：{a.lower()}");
print(f"您输入的话的去掉空格：{a.strip()}");
print(f"您输入的话的反转后：{a[::-1]}");